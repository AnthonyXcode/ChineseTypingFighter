"""Write data/report.md: counts, polyphonic readings, dropped items, random spot-check sample."""
import json
import random
from collections import Counter
import sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))  # noqa: E402
from common import PUBLIC, WORK, DATA, PIPE

SEED = 20261127


def fmt(it):
    py = " ".join(s["pinyin"] for s in it["syllables"])
    jp = " ".join(s["jyutping"] for s in it["syllables"])
    alts = []
    for s in it["syllables"]:
        a = s.get("pinyinAlt", []) + s.get("jyutpingAlt", [])
        if a:
            alts.append(f"{s['hanzi']}:{'/'.join(a)}")
    return py, jp, "; ".join(alts)


def main():
    files = {k: json.loads((PUBLIC / f"{k}.json").read_text(encoding="utf-8"))["items"]
             for k in ("chars", "words", "phrases")}
    dropped = json.loads((WORK / "dropped.json").read_text(encoding="utf-8"))
    L = ["# 奔龍 data pipeline report", "",
         "Generated by `pipeline/report.py`. Source: 倪匡《奔龍》 13 chapters (m.gulongbbs.com).", ""]
    L += ["## Counts", "", "| file | total | L1 | L2 | L3 |", "|---|---|---|---|---|"]
    for k, items in files.items():
        c = Counter(it["level"] for it in items)
        L.append(f"| {k}.json | {len(items)} | {c[1]} | {c[2]} | {c[3]} |")
    L += ["", "### Items by first chapter", "", "| ch | " + " | ".join(files) + " |",
          "|---|" + "---|" * len(files)]
    for ch in range(1, 14):
        L.append(f"| {ch} | " + " | ".join(str(sum(it['chapter'] == ch for it in v)) for v in files.values()) + " |")

    L += ["", "## Polyphonic words — chosen readings (top 100 by frequency)", "",
          "| word | trad | pinyin | jyutping | alternates | freq |", "|---|---|---|---|---|---|"]
    poly = [it for it in files["words"] if any(s["polyphonic"] for s in it["syllables"])]
    poly.sort(key=lambda it: -it["freq"])
    for it in poly[:100]:
        py, jp, alts = fmt(it)
        L.append(f"| {it['text']} | {it['textTrad']} | {py} | {jp} | {alts} | {it['freq']} |")
    L += ["", f"Polyphonic words total: {len(poly)} of {len(files['words'])}."]

    L += ["", "## Dropped items (missing pinyin / jyutping / traditional)", ""]
    if dropped:
        for kind, text, why in dropped:
            L.append(f"- {kind} {text}: {why}")
    else:
        L.append("None — every selected item had pinyin, jyutping and a 1:1 traditional form.")

    rnd = random.Random(SEED)
    pool = [it for v in files.values() for it in v]
    sample = rnd.sample(pool, 50)
    L += ["", f"## Spot-check sample (50 random items, seed {SEED})", "",
          "| id | text | trad | pinyin | jyutping | alternates |", "|---|---|---|---|---|---|"]
    for it in sample:
        py, jp, alts = fmt(it)
        L.append(f"| {it['id']} | {it['text']} | {it['textTrad']} | {py} | {jp} | {alts} |")
    notes = PIPE / "spotcheck_notes.md"
    if notes.exists():
        L += ["", notes.read_text(encoding="utf-8").strip()]
    (DATA / "report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"report: wrote {DATA / 'report.md'}")


if __name__ == "__main__":
    main()
